def provider_supports_city(provider: str, city: str) -> bool:
    """True если у площадки нет ограничений ИЛИ город есть в её whitelist."""
    info = PROVIDER_COVERAGE.get(provider)
    if not info:
        return True
    cities = info.get("departure_cities", "all")
    return cities == "all" or city in cities


def provider_supports_country(provider: str, country: str) -> bool:
    """True если у площадки нет ограничений ИЛИ страна есть в её whitelist."""
    info = PROVIDER_COVERAGE.get(provider)
    if not info:
        return True
    cs = info.get("countries", "all")
    return cs == "all" or country in cs
